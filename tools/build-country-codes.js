/**
 * Builds the data for the enquiry form's phone country-code picker:
 *   js/data/country-codes.js   [ISO code, English name, dialling code] for every country
 *   assets/icons/flags/<iso>.svg   one flag per country (copied unchanged from flag-icons)
 *   node tools/build-country-codes.js
 *
 * Sources (dev dependencies, MIT): libphonenumber-js (official calling codes),
 * flag-icons (SVG flags). Names come from Node's built-in ICU (Intl.DisplayNames).
 * Flags are served from our own domain because the CSP only allows 'self' images.
 */
const fs = require('fs');
const path = require('path');
const { getCountries, getCountryCallingCode } = require('libphonenumber-js');

const ROOT = path.resolve(__dirname, '..');
const FLAG_SRC = path.join(ROOT, 'node_modules', 'flag-icons', 'flags', '4x3');
const FLAG_OUT = path.join(ROOT, 'assets', 'icons', 'flags');
const DATA_OUT = path.join(ROOT, 'js', 'data', 'country-codes.js');

const names = new Intl.DisplayNames(['en'], { type: 'region' });
fs.mkdirSync(FLAG_OUT, { recursive: true });
fs.mkdirSync(path.dirname(DATA_OUT), { recursive: true });

const rows = [];
for (const iso of getCountries()) {
  const flag = path.join(FLAG_SRC, `${iso.toLowerCase()}.svg`);
  if (!fs.existsSync(flag)) {
    console.warn(`skip ${iso}: no flag`);
    continue;
  }
  fs.copyFileSync(flag, path.join(FLAG_OUT, `${iso.toLowerCase()}.svg`));
  rows.push([iso, names.of(iso), getCountryCallingCode(iso)]);
}
rows.sort((a, b) => a[1].localeCompare(b[1], 'en'));

fs.writeFileSync(DATA_OUT, `// Generated by tools/build-country-codes.js — do not edit by hand.
// [ISO 3166-1 alpha-2, English name, international dialling code]
export const COUNTRY_CODES = ${JSON.stringify(rows)};
`);
console.log(`${rows.length} countries → js/data/country-codes.js, flags → assets/icons/flags/`);
